"""Interface language.

Source strings are Simplified Chinese; tr() returns the translation for the
language chosen in the settings (or the system locale). tr() must be called
when a widget is built, never at import time, so that set_language() followed
by rebuilding the window switches the language without a restart.
"""
import locale
import os

from . import settings
from .i18n_ja import JA


def _detect(choice):
    if choice in ('zh', 'en', 'ja'):
        return choice
    code = (os.environ.get('LANGUAGE') or os.environ.get('LC_ALL') or os.environ.get('LC_MESSAGES')
            or os.environ.get('LANG') or (locale.getlocale()[0] or '')).lower()
    return 'zh' if code.startswith('zh') else 'ja' if code.startswith('ja') else 'en'


LANG = _detect(settings.load().get('language', 'auto'))


def set_language(choice):
    """Switch to 'zh', 'en', 'ja' or 'auto' (the system locale)."""
    global LANG
    LANG = _detect(choice)


def tr(text):
    if LANG == 'zh':
        return text
    return (JA if LANG == 'ja' else EN).get(text, text)


